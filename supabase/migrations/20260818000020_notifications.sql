CREATE OR REPLACE FUNCTION public.notify_merchant_application_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' AND NEW.status = 'pending' THEN
    PERFORM public.create_notification(
      NEW.user_id,
      'merchant_application',
      'Application Submitted',
      'Your store application has been submitted and is waiting for review.',
      jsonb_build_object(
        'application_id', NEW.id,
        'store_name', NEW.store_name
      )
    );
    PERFORM public.notify_admins(
      'merchant_application',
      'New Merchant Application',
      'A customer submitted a store application.',
      jsonb_build_object(
        'application_id', NEW.id,
        'store_name', NEW.store_name,
        'user_id', NEW.user_id
      )
    );
  ELSIF TG_OP = 'UPDATE' AND OLD.status IS DISTINCT FROM NEW.status THEN
    IF NEW.status = 'approved' THEN
      PERFORM public.create_notification(
        NEW.user_id,
        'merchant_approved',
        'Store Approved',
        'Your store has been approved. Merchant access is now available.',
        jsonb_build_object(
          'application_id', NEW.id,
          'store_id', NEW.store_id,
          'merchant_id', NEW.merchant_id,
          'unlocked', jsonb_build_array(
            'Shop Details',
            'Wholesale',
            'Products',
            'Store Orders',
            'Wallet'
          )
        )
      );
    ELSIF NEW.status = 'rejected' THEN
      PERFORM public.create_notification(
        NEW.user_id,
        'merchant_rejected',
        'Store Application Rejected',
        'Your store application was rejected.',
        jsonb_build_object(
          'application_id', NEW.id,
          'reason', NEW.rejection_reason
        )
      );
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

