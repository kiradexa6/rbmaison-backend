CREATE OR REPLACE FUNCTION public.notify_admin_action_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid;
  v_title text;
  v_message text;
BEGIN
  IF NEW.action IN ('approve_merchant', 'reject_merchant') THEN
    RETURN NEW;
  END IF;

  v_title := 'Admin Action';
  v_message := coalesce(NEW.description, 'An administrator updated your account.');

  IF NEW.action IN ('suspend_user', 'restore_user') AND NEW.target_type = 'profiles' THEN
    SELECT p.user_id INTO v_user_id FROM public.profiles p WHERE p.id = NEW.target_id;
    v_title := CASE WHEN NEW.action = 'suspend_user' THEN 'Account Suspended' ELSE 'Account Restored' END;
  ELSIF NEW.action IN ('add_funds', 'remove_funds') AND NEW.target_type = 'wallets' THEN
    SELECT m.user_id INTO v_user_id
    FROM public.wallets w
    JOIN public.merchants m ON m.id = w.merchant_id
    WHERE w.id = NEW.target_id;
    v_title := 'Wallet Balance Updated';
  ELSIF NEW.action = 'adjust_credit_score' THEN
    SELECT m.user_id INTO v_user_id
    FROM public.merchant_credit_scores cs
    JOIN public.merchants m ON m.id = cs.merchant_id
    WHERE cs.id = NEW.target_id;
    v_title := 'Credit Score Updated';
  ELSIF NEW.action IN ('suspend_store', 'approve_store') AND NEW.target_type = 'stores' THEN
    SELECT m.user_id INTO v_user_id
    FROM public.stores s
    JOIN public.merchants m ON m.id = s.merchant_id
    WHERE s.id = NEW.target_id;
    v_title := CASE WHEN NEW.action = 'suspend_store' THEN 'Store Suspended' ELSE 'Store Activated' END;
  ELSIF NEW.action IN ('enable_wholesale_access', 'suspend_wholesale_access') THEN
    SELECT m.user_id INTO v_user_id FROM public.merchants m WHERE m.id = NEW.target_id;
    v_title := 'Wholesale Access Updated';
  ELSE
    RETURN NEW;
  END IF;

  IF v_user_id IS NULL OR v_user_id = NEW.admin_id THEN
    RETURN NEW;
  END IF;

  PERFORM public.create_notification(
    v_user_id,
    'admin_action',
    v_title,
    v_message,
    jsonb_build_object(
      'action', NEW.action,
      'target_type', NEW.target_type,
      'target_id', NEW.target_id,
      'log_id', NEW.id
    )
  );

  RETURN NEW;
END;
$$;

