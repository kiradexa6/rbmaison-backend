CREATE OR REPLACE FUNCTION public.notify_order_payment_required(p_order_id uuid)
RETURNS public.notifications
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_order public.orders;
  v_user_id uuid;
  v_payload jsonb;
  v_row public.notifications;
BEGIN
  SELECT * INTO v_order
  FROM public.orders
  WHERE id = p_order_id;

  IF v_order.id IS NULL THEN
    RAISE EXCEPTION 'Order not found';
  END IF;

  v_user_id := public.merchant_user_id(v_order.merchant_id);
  v_payload := public.order_notification_payload(v_order.id);

  v_row := public.create_notification(
    v_user_id,
    'order_payment_required',
    'Payment Required',
    'Wholesale payment failed. Please top up your account.',
    v_payload
  );

  PERFORM public.notify_admins(
    'admin_action',
    'Suspicious Activity',
    'A merchant order payment failed due to insufficient wholesale balance.',
    v_payload || jsonb_build_object('reason', 'insufficient_wholesale_balance')
  );

  RETURN v_row;
END;
$$;

