-- R&B MAISON — production notification system
-- Notifications are created only from committed backend events. Clients cannot insert.

CREATE TYPE public.notification_type AS ENUM (
  'merchant_application',
  'merchant_approved',
  'merchant_rejected',
  'new_order',
  'order_payment_required',
  'order_paid',
  'shipping_confirmed',
  'delivery_completed',
  'profit_released',
  'deposit_pending',
  'deposit_approved',
  'deposit_rejected',
  'withdrawal_pending',
  'withdrawal_approved',
  'withdrawal_rejected',
  'admin_action'
);

CREATE TYPE public.notification_read_status AS ENUM ('unread', 'read');

CREATE TABLE public.notifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  type public.notification_type NOT NULL,
  title text NOT NULL,
  message text NOT NULL,
  data jsonb NOT NULL DEFAULT '{}'::jsonb,
  read_status public.notification_read_status NOT NULL DEFAULT 'unread',
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT notifications_title_chk CHECK (char_length(btrim(title)) BETWEEN 1 AND 120),
  CONSTRAINT notifications_message_chk CHECK (char_length(btrim(message)) BETWEEN 1 AND 500),
  CONSTRAINT notifications_data_chk CHECK (jsonb_typeof(data) = 'object'),
  CONSTRAINT notifications_read_at_chk CHECK (
    (read_status = 'unread' AND read_at IS NULL)
    OR (read_status = 'read' AND read_at IS NOT NULL)
  )
);

CREATE INDEX idx_notifications_user_created
  ON public.notifications (user_id, created_at DESC);
CREATE INDEX idx_notifications_user_unread
  ON public.notifications (user_id)
  WHERE read_status = 'unread';
CREATE INDEX idx_notifications_type ON public.notifications (type);

COMMENT ON TABLE public.notifications IS
  'In-app notifications generated by backend events. Clients cannot create or edit content.';

CREATE TRIGGER trg_notifications_set_updated_at
  BEFORE UPDATE ON public.notifications
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

