CREATE OR REPLACE FUNCTION public.protect_notification_columns()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Notifications cannot be deleted';
  END IF;

  IF NEW.user_id IS DISTINCT FROM OLD.user_id
     OR NEW.type IS DISTINCT FROM OLD.type
     OR NEW.title IS DISTINCT FROM OLD.title
     OR NEW.message IS DISTINCT FROM OLD.message
     OR NEW.data IS DISTINCT FROM OLD.data
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'Notification content cannot be changed';
  END IF;

  IF NEW.read_status IS DISTINCT FROM OLD.read_status
     AND NOT (
       OLD.read_status = 'unread'
       AND NEW.read_status = 'read'
     ) THEN
    RAISE EXCEPTION 'Notifications can only be marked read';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_notifications_protect
  BEFORE UPDATE OR DELETE ON public.notifications
  FOR EACH ROW
  EXECUTE FUNCTION public.protect_notification_columns();

