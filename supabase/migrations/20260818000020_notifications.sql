CREATE OR REPLACE FUNCTION public.notify_profit_release_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid;
BEGIN
  IF NEW.type <> 'profit_release' OR NEW.status <> 'completed' THEN
    RETURN NEW;
  END IF;

  SELECT m.user_id INTO v_user_id
  FROM public.wallets w
  JOIN public.merchants m ON m.id = w.merchant_id
  WHERE w.id = NEW.wallet_id;

  IF v_user_id IS NULL THEN
    RETURN NEW;
  END IF;

  PERFORM public.create_notification(
    v_user_id,
    'profit_released',
    'Profit Released',
    'Your order profit has been released.',
    jsonb_build_object(
      'amount', NEW.amount,
      'currency', NEW.currency,
      'order_id', NEW.reference_id,
      'transaction_id', NEW.id
    )
  );

  RETURN NEW;
END;
$$;

