CREATE OR REPLACE FUNCTION public.create_notification(
  p_user_id uuid,
  p_type public.notification_type,
  p_title text,
  p_message text,
  p_data jsonb DEFAULT '{}'::jsonb
)
RETURNS public.notifications
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row public.notifications;
BEGIN
  IF p_user_id IS NULL THEN
    RAISE EXCEPTION 'Notification user is required';
  END IF;

  INSERT INTO public.notifications (
    user_id,
    type,
    title,
    message,
    data
  )
  VALUES (
    p_user_id,
    p_type,
    btrim(p_title),
    btrim(p_message),
    COALESCE(p_data, '{}'::jsonb)
  )
  RETURNING * INTO v_row;

  RETURN v_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.notify_admins(
  p_type public.notification_type,
  p_title text,
  p_message text,
  p_data jsonb DEFAULT '{}'::jsonb
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_admin record;
  v_count integer := 0;
BEGIN
  FOR v_admin IN
    SELECT p.user_id
    FROM public.profiles p
    WHERE p.role = 'admin'
      AND p.status = 'active'
  LOOP
    PERFORM public.create_notification(
      v_admin.user_id,
      p_type,
      p_title,
      p_message,
      p_data
    );
    v_count := v_count + 1;
  END LOOP;

  RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.order_notification_payload(p_order_id uuid)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT jsonb_build_object(
    'order_id', o.id,
    'store_id', o.store_id,
    'store', s.store_name,
    'merchant_id', o.merchant_id,
    'amount', o.total_amount,
    'currency', o.currency,
    'product', coalesce(
      (
        SELECT string_agg(pr.name, ', ' ORDER BY oi.created_at)
        FROM public.order_items oi
        JOIN public.products pr ON pr.id = oi.product_id
        WHERE oi.order_id = o.id
      ),
      ''
    )
  )
  FROM public.orders o
  LEFT JOIN public.stores s ON s.id = o.store_id
  WHERE o.id = p_order_id;
$$;

CREATE OR REPLACE FUNCTION public.merchant_user_id(p_merchant_id uuid)
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT m.user_id
  FROM public.merchants m
  WHERE m.id = p_merchant_id;
$$;

